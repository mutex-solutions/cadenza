#!/bin/sh
# Generate the Homebrew formula for a released version from its checksums.txt.
# Usage: scripts/gen-formula.sh <version-without-v> [checksums-file] > Formula/cadenza.rb
# The formula installs the agent-side `cadenza` command only.
set -eu

ver="${1:?usage: gen-formula.sh <version e.g. 0.1.0> [checksums-file]}"
repo="mutex-solutions/cadenza"
base="https://github.com/$repo/releases/download/v$ver"

if [ "${2:-}" != "" ] && [ -f "$2" ]; then
  sums=$(cat "$2")
else
  sums=$(curl -fsSL "$base/checksums.txt")
fi
sha() { echo "$sums" | grep " cadenza_$1\$" | cut -d' ' -f1; }

d_arm=$(sha darwin_arm64.tar.gz)
d_amd=$(sha darwin_amd64.tar.gz)
l_arm=$(sha linux_arm64.tar.gz)
l_amd=$(sha linux_amd64.tar.gz)

for v in "$d_arm" "$d_amd" "$l_arm" "$l_amd"; do
  [ -n "$v" ] || { echo "missing a checksum for v$ver in checksums.txt" >&2; exit 1; }
done

cat <<FORMULA
# typed: false
# frozen_string_literal: true

# Homebrew formula for cadenza, the command coding agents use to show their
# work and ask you questions. Regenerated by scripts/gen-formula.sh on each
# release; do not edit by hand.
class Cadenza < Formula
  desc "Let coding agents show their work and ask you questions"
  homepage "https://github.com/$repo"
  version "$ver"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$base/cadenza_darwin_arm64.tar.gz"
      sha256 "$d_arm"
    end
    on_intel do
      url "$base/cadenza_darwin_amd64.tar.gz"
      sha256 "$d_amd"
    end
  end

  on_linux do
    on_arm do
      url "$base/cadenza_linux_arm64.tar.gz"
      sha256 "$l_arm"
    end
    on_intel do
      url "$base/cadenza_linux_amd64.tar.gz"
      sha256 "$l_amd"
    end
  end

  def install
    bin.install "cadenza"
  end

  test do
    assert_match "cadenza", shell_output("#{bin}/cadenza version")
  end
end
FORMULA
