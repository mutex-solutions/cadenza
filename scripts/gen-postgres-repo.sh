#!/bin/sh
# Generate internal/adapter/sqlstore/postgres/repo.go from the SQLite one.
# The two engines share queries, so their sqlc output has the same Go API and
# the repository code is identical apart from the package and import path.
set -eu
src=internal/adapter/sqlstore/sqlite/repo.go
dst=internal/adapter/sqlstore/postgres/repo.go
{
  echo "// Code generated by scripts/gen-postgres-repo.sh from sqlite/repo.go. DO NOT EDIT."
  echo
  sed -e 's/^package sqlite$/package postgres/' \
      -e 's#internal/adapter/sqlstore/sqlite/db"#internal/adapter/sqlstore/postgres/db"#' \
      -e '/^\/\/ This file is the source of postgres\/repo.go/,/^$/d' \
      "$src"
} > "$dst"
gofmt -w "$dst"
