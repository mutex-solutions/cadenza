package main

import (
	"encoding/json"
	"fmt"
	"reflect"
	"sort"
	"strings"

	"github.com/mutex-solutions/cadenza/internal/spec"
)

var rawMessage = reflect.TypeOf(json.RawMessage{})

// TypeScript renders every wire type reachable from spec.Endpoints as a
// TypeScript interface, plus the endpoint table and the spec constants.
func TypeScript() string {
	var b strings.Builder
	b.WriteString("// Code generated by cmd/cadenza-gen from internal/spec. DO NOT EDIT.\n\n")
	types := map[string]reflect.Type{}
	var collect func(reflect.Type)
	collect = func(t reflect.Type) {
		for t.Kind() == reflect.Pointer || t.Kind() == reflect.Slice || t.Kind() == reflect.Map {
			t = t.Elem()
		}
		if t.Kind() != reflect.Struct || t == rawMessage {
			return
		}
		if _, seen := types[t.Name()]; seen {
			return
		}
		types[t.Name()] = t
		for i := range t.NumField() {
			collect(t.Field(i).Type)
		}
	}
	for _, e := range spec.Endpoints {
		for _, v := range []any{e.Input, e.Output} {
			if v != nil {
				collect(reflect.TypeOf(v))
			}
		}
	}
	collect(reflect.TypeOf(spec.Error{}))
	names := make([]string, 0, len(types))
	for n := range types {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		writeInterface(&b, types[n])
	}

	b.WriteString("export type Auth = \"none\" | \"machine\" | \"session\" | \"owner\" | \"any\";\n\n")
	b.WriteString("export interface Endpoint {\n  method: \"GET\" | \"POST\" | \"DELETE\";\n  path: string;\n  auth: Auth;\n  summary: string;\n}\n\n")
	b.WriteString("export const endpoints = {\n")
	for _, e := range spec.Endpoints {
		fmt.Fprintf(&b, "  %q: { method: %q, path: %q, auth: %q, summary: %s },\n", e.Name, e.Method, e.Path, e.Auth, jsString(e.Summary))
	}
	b.WriteString("} as const satisfies Record<string, Endpoint>;\n\n")
	b.WriteString("export type EndpointName = keyof typeof endpoints;\n\n")
	b.WriteString("/** Request and response body types per endpoint (void when there is none). */\n")
	b.WriteString("export interface EndpointTypes {\n")
	for _, e := range spec.Endpoints {
		fmt.Fprintf(&b, "  %q: { input: %s; output: %s };\n", e.Name, tsName(e.Input), tsName(e.Output))
	}
	b.WriteString("}\n\n")

	consts := []struct{ name, value string }{
		{"QuestionOpen", spec.QuestionOpen}, {"QuestionAnswered", spec.QuestionAnswered}, {"QuestionReplaced", spec.QuestionReplaced},
		{"QuestionDismissed", spec.QuestionDismissed}, {"ReplyAnswer", spec.ReplyAnswer}, {"ReplyNote", spec.ReplyNote},
		{"ReplyVerdict", spec.ReplyVerdict}, {"ReplyComment", spec.ReplyComment}, {"ReplySketch", spec.ReplySketch},
		{"VerdictApprove", spec.VerdictApprove}, {"VerdictRequestChanges", spec.VerdictRequestChanges},
		{"ThreadActive", spec.ThreadActive}, {"ThreadChangesRequested", spec.ThreadChangesRequested}, {"ThreadReady", spec.ThreadReady},
		{"ThreadApproved", spec.ThreadApproved}, {"ThreadArchived", spec.ThreadArchived},
		{"PairPending", spec.PairPending}, {"PairApproved", spec.PairApproved}, {"PairExpired", spec.PairExpired},
		{"EventThreadCreated", spec.EventThreadCreated}, {"EventThreadStatus", spec.EventThreadStatus}, {"EventThreadReady", spec.EventThreadReady},
		{"EventPostAdded", spec.EventPostAdded}, {"EventQuestionAsked", spec.EventQuestionAsked}, {"EventQuestionChanged", spec.EventQuestionChanged},
		{"EventReplyAdded", spec.EventReplyAdded}, {"EventReplyDelivered", spec.EventReplyDelivered}, {"EventAgentReplied", spec.EventAgentReplied},
		{"EventMachineChanged", spec.EventMachineChanged},
	}
	for _, c := range consts {
		fmt.Fprintf(&b, "export const %s = %q;\n", c.name, c.value)
	}
	fmt.Fprintf(&b, "export const APIVersion = %d;\n", spec.APIVersion)
	return b.String()
}

func tsName(v any) string {
	if v == nil {
		return "void"
	}
	return reflect.TypeOf(v).Name()
}

func jsString(s string) string {
	b, _ := json.Marshal(s)
	return string(b)
}

func writeInterface(b *strings.Builder, t reflect.Type) {
	var extends []string
	var fields []string
	for i := range t.NumField() {
		f := t.Field(i)
		if f.Anonymous {
			extends = append(extends, f.Type.Name())
			continue
		}
		tag := f.Tag.Get("json")
		name, opts, _ := strings.Cut(tag, ",")
		if name == "-" || name == "" {
			continue
		}
		optional := strings.Contains(opts, "omitempty") || f.Type.Kind() == reflect.Pointer
		q := ""
		if optional {
			q = "?"
		}
		doc := f.Tag.Get("jsonschema")
		line := ""
		if doc != "" {
			line = "  /** " + doc + " */\n"
		}
		fields = append(fields, fmt.Sprintf("%s  %s%s: %s;", line, name, q, tsType(f.Type)))
	}
	ext := ""
	if len(extends) > 0 {
		ext = " extends " + strings.Join(extends, ", ")
	}
	fmt.Fprintf(b, "export interface %s%s {\n%s\n}\n\n", t.Name(), ext, strings.Join(fields, "\n"))
}

func tsType(t reflect.Type) string {
	if t == rawMessage {
		return "unknown"
	}
	switch t.Kind() {
	case reflect.Pointer:
		return tsType(t.Elem())
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Slice:
		return tsType(t.Elem()) + "[]"
	case reflect.Map:
		return "Record<string, " + tsType(t.Elem()) + ">"
	case reflect.Struct:
		return t.Name()
	case reflect.Interface:
		return "unknown"
	}
	panic("cadenza-gen: unsupported type " + t.String())
}
